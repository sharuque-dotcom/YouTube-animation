"""Split one voice take into per-line clips using word timestamps (e.g. from a speech-to-text pass).

Usage: python3 pipeline/split_by_words.py episodes/<ep> raw/<take>.mp3 words.txt OFFSET
words.txt: one "word start end" per line, times in seconds; OFFSET is subtracted (for a batch transcript).
Each narration line becomes <ep>/voice/main-N.wav cut from just before its first word to just after its
last word; writes <ep>/align.js with exact word start times (narration words matched to the transcript).
"""
import json, re, subprocess, sys, difflib
from pathlib import Path
ep = Path(sys.argv[1]); src = ep / sys.argv[2]; off = float(sys.argv[4])
dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(src)], capture_output=True, text=True).stdout)
W = []
for ln in Path(sys.argv[3]).read_text().splitlines():
    w, a, b = ln.rsplit(' ', 2); a, b = float(a) - off, float(b) - off
    if -0.3 <= a <= dur + 0.3: W.append((w, a, b))
lines = [l['text'] for l in json.loads((ep / 'narration.json').read_text())['scenes'][0]['lines']]
norm = lambda s: re.sub(r"[^\wഀ-ൿ]", '', s)
def nchar(s): return sum(4 if c.isdigit() else 1 for c in norm(s)) or 1
# assign transcript words to lines: greedy by cumulative char share, then snap to the biggest gap nearby
tw = [norm(w) for w, _, _ in W]
NW = [l.split() for l in lines]; flat = [(i, w) for i, ws in enumerate(NW) for w in ws]
sm = difflib.SequenceMatcher(None, [norm(w) for _, w in flat], tw, autojunk=False)
anchor = {}
for blk in sm.get_matching_blocks():
    for k in range(blk.size): anchor[blk.a + k] = blk.b + k
# line boundaries: given as absolute start times of each line's first word (argv[5], comma-separated), else from anchors
if len(sys.argv) > 5:
    S = [float(x) - off for x in sys.argv[5].split(',')]
    idx = lambda t: min(range(len(W)), key=lambda k: abs(W[k][1] - t))
    starts = [idx(x) for x in S]; ends = [starts[i + 1] - 1 for i in range(len(starts) - 1)] + [len(W) - 1]
    # anchors only inside the right line
    li_of = lambda k: max(i for i in range(len(starts)) if starts[i] <= k)
    anchor = {a: b for a, b in anchor.items() if li_of(b) == flat[a][0]}
else:
    raise SystemExit('pass line start times')
(ep / 'voice').mkdir(exist_ok=True); ALIGN = []; fk = 0
for i, l in enumerate(lines):
    a = max(0, W[starts[i]][1] - 0.06); b = min(dur, W[ends[i]][2] + 0.14)
    out = ep / 'voice' / f'main-{i + 1}.wav'
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', str(src), '-af', f'atrim={a:.3f}:{b:.3f},asetpts=PTS-STARTPTS,afade=t=in:d=0.02,areverse,afade=t=in:d=0.05,areverse', '-ar', '44100', '-ac', '1', str(out)], check=True)
    ws = NW[i]; ks = list(range(fk, fk + len(ws))); fk += len(ws)
    t = [None] * len(ws)
    for j, k in enumerate(ks):
        if k in anchor: t[j] = W[anchor[k]][1] - a
    t[0] = t[0] if t[0] is not None else W[starts[i]][1] - a
    endt = W[ends[i]][2] - a
    j = 0
    while j < len(ws):
        if t[j] is None:
            p = j - 1; q = j
            while q < len(ws) and t[q] is None: q += 1
            t1 = t[q] if q < len(ws) else endt
            # spread the gap words by char weight, starting at the previous word's end estimate
            wts = [nchar(ws[x]) for x in range(p, q)]; tot = sum(wts); acc = 0
            for x in range(p + 1, q): acc += wts[x - 1 - p]; t[x] = t[p] + (t1 - t[p]) * acc / tot
            j = q
        j += 1
    ALIGN.append([[w, round(x, 3)] for w, x in zip(ws, t)])
    print(f'line {i + 1}: {a:6.2f}-{b:6.2f} ({b - a:5.2f}s) {l[:36]}')
(ep / 'align.js').write_text('// generated by pipeline/split_by_words.py: word start times (s from line cue), from a speech-to-text pass\nexport const ALIGN = ' + json.dumps(ALIGN, ensure_ascii=False) + ';\n')
