"""Word timing from pauses (no speech model needed).

For each narration line, finds the pauses inside the recorded clip and matches the
text's phrases (split at punctuation) to the stretches of speech between them, then
spreads the words of each phrase by spoken length (digits count as long words).
Writes <episode>/align.js: export const ALIGN = [[ [word, startSec], ... ], ...] per line,
times relative to the line's cue start.

Usage: python3 pipeline/align_pauses.py episodes/<ep>   (after pipeline/tts.py)
"""
import json, re, subprocess, sys, functools
from pathlib import Path

ep = Path(sys.argv[1]); build = Path(__file__).resolve().parent.parent / 'build' / ep.name
spec = json.loads((ep / 'narration.json').read_text())

def weight(w):
    return sum(7 if c.isdigit() else 1 for c in w) + 1

def speech_segments(wav):
    out = subprocess.run(['ffmpeg', '-i', str(wav), '-af', 'silencedetect=noise=-38dB:d=0.1', '-f', 'null', '-'], capture_output=True, text=True).stderr
    dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(wav)], capture_output=True, text=True).stdout)
    st = [float(x) for x in re.findall(r'silence_start: (-?[\d.]+)', out)]; en = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', out)]
    segs, prev = [], 0.0
    for a, b in zip(st, en + [dur] * (len(st) - len(en))):
        if a > prev + 0.04: segs.append((prev, a))
        prev = b
    if dur > prev + 0.04: segs.append((prev, dur))
    return segs

ALIGN = []
for scene in spec['scenes']:
    for i, line in enumerate(scene['lines'], 1):
        text = line['text'] if isinstance(line, dict) else line
        words = text.split(); W = [weight(w) for w in words]
        segs = speech_segments(build / 'clips' / f"{scene['id']}-{i}.wav")
        n, k = len(words), len(segs)
        rate = sum(b - a for a, b in segs) / sum(W)
        brk = [bool(re.search(r'[.,:;?!"”]$|\.\.\.$', w)) for w in words]
        pre = [0]
        for x in W: pre.append(pre[-1] + x)
        @functools.lru_cache(None)
        def best(wi, si):  # place words[wi:] into segs[si:]
            if si == k: return (0.0, ()) if wi == n else (1e9, ())
            if wi == n: return (1e9, ())
            res = (1e9, ())
            last = si == k - 1
            for wj in range(wi + 1, n + 1):
                if not last and wj == n: break
                if last and wj != n: continue
                pen = 0 if (wj == n or brk[wj - 1]) else 0.6
                d = segs[si][1] - segs[si][0]; pred = (pre[wj] - pre[wi]) * rate
                sub = best(wj, si + 1)
                c = (d - pred) ** 2 + pen + sub[0]
                if c < res[0]: res = (c, (wj,) + sub[1])
            return res
        if k <= n:
            ends = best(0, 0)[1]
        else:  # more pauses than words: fall back to one segment
            segs = [(segs[0][0], segs[-1][1])]; ends = (n,)
        out, wi = [], 0
        for (a, b), wj in zip(segs, ends):
            tot = pre[wj] - pre[wi]; acc = 0
            for q in range(wi, wj):
                out.append([words[q], round(a + (b - a) * acc / tot, 3)]); acc += W[q]
            wi = wj
        ALIGN.append(out)
        print(i, ' | '.join(f"{w}@{t}" for w, t in out)[:300])

(ep / 'align.js').write_text('// generated by pipeline/align_pauses.py: word start times (s from line cue)\nexport const ALIGN = ' + json.dumps(ALIGN, ensure_ascii=False) + ';\n')
